/**
 * Assemble everything publishable into `site/`. `node tools/build-site.ts`
 *
 * Three pages, and they are for three different readers:
 *
 *   - **`/app/`** — the interactive simulator. For somebody who wants to
 *     understand what a projected sphere does and what calibrating one buys.
 *   - **`/harness/`** — the developer harness. Five viewports, a slider per
 *     constant carrying its provenance class, and the GPU↔CPU parity number.
 *   - **`/progress/`** — the measurement record, if one has been generated.
 *
 * The landing page is written here rather than kept as a file, because it is
 * nothing but links and a paragraph and a separate file would drift out of date
 * with what the directory actually contains: this one is generated FROM what
 * was found.
 *
 * ## What is deliberately not published
 *
 * `validation/`. It holds photographs of real installations beside our render,
 * and PARAMETERS.md's brief is explicit that provenance is unknown until the
 * owner says otherwise — NOAA imagery is generally public domain but
 * site-submitted photographs may not be. A page that is not published cannot
 * republish somebody's photograph by accident.
 */

