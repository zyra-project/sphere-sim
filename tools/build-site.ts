function main(): void {
  fs.rmSync(SITE, { recursive: true, force: true });
  fs.mkdirSync(SITE, { recursive: true });

  const published: Page[] = [];
  for (const page of PAGES) {
    if (!fs.existsSync(path.join(ROOT, page.requires))) {
      console.log(`  skip  ${page.slug}  (${page.requires} is not built)`);
      continue;
    }
    let files = 0;
    for (const src of page.sources) {
      const from = path.join(ROOT, src.from);
      if (!fs.existsSync(from)) continue;
      files += copyRecursive(from, path.join(SITE, page.slug, src.to));
    }
    console.log(`  ok    ${page.slug}  ${files} file(s)`);
    published.push(page);
  }

  if (published.length === 0) {
    console.error('\nnothing to publish. Run `npm run build:app` and `npm run build:web` first.\n');
    process.exitCode = 1;
    return;
  }

  fs.writeFileSync(path.join(SITE, 'index.html'), landingPage(published));
  // GitHub Pages runs Jekyll by default, which silently drops any path with a
  // leading underscore. Nothing here has one today; the file costs nothing and
  // the failure mode it prevents is a missing asset with no error anywhere.
  fs.writeFileSync(path.join(SITE, '.nojekyll'), '');
  console.log(`\nwrote site/ — ${published.length} page(s) plus a landing page\n`);
}

main();
